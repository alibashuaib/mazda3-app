#!/usr/bin/env node
/* Regenerates supabase/seed-parts.sql from src/data/catalog.js sharedParts, so
   every built-in part price exists server-side as a baseline row (Phase 4,
   D-04/D-07: price materiality needs a live value to compare against). Run
   after any catalog.js change:
     node tools/seed-parts.js
   Apply AFTER seed-catalogue.sql (foreign key to car_models).
   test/seed-parts.test.js fails while the committed file is stale. */
'use strict';
const fs = require('fs');
const path = require('path');
const cat = require('../src/data/catalog.js');

const slug = (s) => String(s || '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 40).replace(/-+$/, '');

function partRows() {
  const rows = [];
  for (const m of cat.CAR_MODELS) {
    for (const [engine] of m.engines) {
      const id = cat.catalogId(m.id, engine);
      const seen = new Set();
      for (const p of cat.sharedParts(m.id, engine)) {
        for (const o of p.options) {
          const slot = o.tag === 'OEM' ? 'oem' : 'alt:' + (slug(o.brand) || 'other');
          const key = p.name + '|' + slot;
          if (seen.has(key)) continue;   // first option wins for a repeated slot
          seen.add(key);
          const dealer = o.tag === 'OEM' && String(o.note || '').includes('Mazda KSA dealer price list');
          rows.push({ car_model_id: id, part_name: p.name, slot, brand: o.brand || '', part_no: o.partNo || '',
            price: Number(o.price) > 0 ? Number(o.price) : null,
            price_basis: dealer ? 'dealer' : 'static', note: o.note || '' });
        }
      }
    }
  }
  return rows;
}

/* Dollar-quoted JSON fed through jsonb_to_recordset (no per-value escaping).
   `on conflict do nothing`: a re-run never reverts an approved value. */
function seedSql(rows) {
  const j = JSON.stringify(rows);
  if (j.includes('$seed$')) throw new Error('seed data contains the $seed$ quote tag');
  return `-- GENERATED by tools/seed-parts.js from src/data/catalog.js. Do not edit.
-- Apply after schema.sql and seed-catalogue.sql (FK to car_models). Idempotent: existing rows are left alone.
insert into public.catalogue_parts (car_model_id, part_name, slot, brand, part_no, price, price_basis, note)
select car_model_id, part_name, slot, brand, part_no, price, price_basis, note
from jsonb_to_recordset($seed$${j}$seed$::jsonb)
  as r(car_model_id text, part_name text, slot text, brand text, part_no text, price numeric, price_basis text, note text)
on conflict (car_model_id, part_name, slot) do nothing;
`;
}

if (require.main === module) {
  fs.writeFileSync(path.join(__dirname, '..', 'supabase', 'seed-parts.sql'), seedSql(partRows()));
  console.log('wrote supabase/seed-parts.sql');
}

module.exports = { partRows, seedSql };
